YiRomProfile YiIdentifyRom(const uint8_t *data, size_t size) {
  static const uint32_t crc[2] = {0xd138f224u, 0x07e01ef9u};
  if (!data) return YI_ROM_UNSUPPORTED;
  if (size == YI_ROM_SIZE + 512u) { data += 512; size -= 512; }
  if (size != YI_ROM_SIZE) return YI_ROM_UNSUPPORTED;
  uint8_t sha[32];
  sha256_compute(data, size, sha);
  for (int i = 0; i < 2; ++i)
    if (!memcmp(sha, yi_known_sha256[i], 32) && crc32_compute(data, size) == crc[i])
      return (YiRomProfile)i;
  return YI_ROM_UNSUPPORTED;
}

int YiRomIsPal(YiRomProfile profile) { return profile == YI_ROM_EU_11; }
double YiRomFrameRate(YiRomProfile profile) {
  /* PAL colourburst * 4.8, 312 non-interlaced lines of 1364 clocks. */
  return YiRomIsPal(profile) ? 21281370.0 / (1364.0 * 312.0) : 60.09881389744051;
}
